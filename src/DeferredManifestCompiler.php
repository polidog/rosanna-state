<?php

declare(strict_types=1);

namespace Polidog\Rosanna\State;

use Polidog\Rosanna\Psx\CompileCommand;
use Polidog\Rosanna\Runtime\PsxRenderer;

/**
 * `rosanna-state compile` が `CompileCommand` の manifest の後に動かし、defer の登録を deferred manifest に書く。
 *
 * @internal
 */
final class DeferredManifestCompiler
{
    private const string GENERATED_COMMENT = '// Auto-generated by `rosanna-state compile`. Do not edit.';

    /**
     * defer がなくても必ず書き、manifest と同じ build ID を持つ (CP-136)。
     *
     * @param array<string, string> $components FQCN => ソースのパス
     *
     * @return list<string> 古い (書き換えた) パス
     */
    public function compile(array $components, string $cacheDir, string $buildId, bool $check): array
    {
        $path = $cacheDir . \DIRECTORY_SEPARATOR . PsxRenderer::DEFERRED_MANIFEST_FILENAME;
        $entries = $this->collectDeferred($components, $cacheDir);

        \ksort($entries, \SORT_STRING);
        $lines = ['<?php', self::GENERATED_COMMENT, 'return ['];
        $lines[] = '    ' . \var_export(PsxRenderer::BUILD_ID_KEY, true) . ' => ' . \var_export($buildId, true) . ',';
        foreach ($entries as $name => $entry) {
            $lines[] = '    ' . \var_export((string) $name, true) . ' => ['
                . "'component' => " . \var_export($entry['component'], true)
                . ", 'cacheControl' => " . \var_export($entry['cacheControl'], true)
                . '],';
        }
        $lines[] = '];';

        return CompileCommand::writeIfChanged($path, \implode("\n", $lines) . "\n", $check) ? [$path] : [];
    }

    /**
     * manifest の隣の deferred manifest を読み、build ID を照合する。ファイルの有無だけを見ると、
     * `rosanna-state compile` の後の `rosanna compile` で古い登録を受け入れてしまう。
     *
     * @return array<string, array{component: string, cacheControl: ?string}> 名前 => 登録の内容
     * @throws \RuntimeException ファイルがない、build ID が合わない、項目の形が違うとき
     */
    public static function read(string $manifestPath): array
    {
        $path = \dirname($manifestPath) . \DIRECTORY_SEPARATOR . PsxRenderer::DEFERRED_MANIFEST_FILENAME;
        if (!\file_exists($path)) {
            throw new \RuntimeException("Deferred manifest not found: {$path}. RosannaState needs `vendor/bin/rosanna-state compile`, not `vendor/bin/rosanna compile`.");
        }

        $data = PsxRenderer::readArrayFile($path);
        if (($data[PsxRenderer::BUILD_ID_KEY] ?? null) !== PsxRenderer::readBuildId($manifestPath) || !isset($data[PsxRenderer::BUILD_ID_KEY])) {
            throw new \RuntimeException("Deferred manifest {$path} does not match {$manifestPath}. Run `vendor/bin/rosanna-state compile` to regenerate.");
        }
        unset($data[PsxRenderer::BUILD_ID_KEY]);

        $deferred = [];
        foreach ($data as $name => $entry) {
            $cacheControl = \is_array($entry) ? ($entry['cacheControl'] ?? null) : null;
            // `404` のような数字だけの名前は PHP の配列のキーで整数になる
            if (!\is_array($entry) || !\is_string($entry['component'] ?? null) || (!\is_string($cacheControl) && $cacheControl !== null)) {
                throw new \RuntimeException("Invalid deferred manifest entry in {$path}. Run `vendor/bin/rosanna-state compile` to regenerate.");
            }
            $deferred[(string) $name] = ['component' => $entry['component'], 'cacheControl' => $cacheControl];
        }

        return $deferred;
    }

    /**
     * CP-135: `Defer` の文字列を含むファイルだけを読み込む。トップレベルのコードが実行される。
     *
     * @param array<string, string> $components FQCN => ソースのパス
     *
     * @return array<array-key, array{component: string, cacheControl: ?string}>
     */
    private function collectDeferred(array $components, string $cacheDir): array
    {
        \ksort($components, \SORT_STRING);

        $entries = [];
        foreach ($components as $fqcn => $file) {
            $artifactPath = CompileCommand::cachePathFor($cacheDir, $file);
            $artifact = \is_file($artifactPath) ? @\file_get_contents($artifactPath) : false;
            if ($artifact === false || !\str_contains($artifact, 'Defer')) {
                continue;
            }

            \ob_start();
            try {
                $value = require $artifactPath;
            } catch (\Throwable $e) {
                throw new \RuntimeException(
                    "Error: failed to load $artifactPath ($file) while scanning for deferred components: " . $e->getMessage(),
                    previous: $e,
                );
            } finally {
                \ob_end_clean();
            }

            if (!$value instanceof FunctionComponent || $value->defer === null) {
                continue;
            }

            $name = $value->defer->name;
            if (isset($entries[$name])) {
                throw new \RuntimeException(
                    "Error: duplicate deferred component name '$name'\n"
                    . "  registered by: {$entries[$name]['component']}\n  also by:       $fqcn",
                );
            }
            $entries[$name] = ['component' => $fqcn, 'cacheControl' => $value->defer->cacheControl];
        }

        return $entries;
    }
}
